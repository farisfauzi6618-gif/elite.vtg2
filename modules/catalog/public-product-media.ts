import {put,del} from '@vercel/blob';
import {getSqlClient} from '@/lib/database';
import {publishedPhoto} from './photo-publication';
import type {PhotoBytes,PhotoPreviewSize} from './photo-preview';
import type {Product} from './catalog-types';

// Public derivatives only. This token must belong to a SEPARATE public store.
// Never fall back to BLOB_READ_WRITE_TOKEN (originals, drafts and proofs).
const token=()=>process.env.PRODUCT_MEDIA_READ_WRITE_TOKEN?.trim();
export const PUBLIC_MEDIA_PIPELINE='preview-v1';
export const PUBLIC_MEDIA_FILE_LIMIT=512*1024;
export const PUBLIC_MEDIA_TOTAL_LIMIT=128*1024*1024;
const LEASE_MS=120_000;
type Row={photo_key:string;preset:PhotoPreviewSize;pipeline:string;state:string;lease_id:string;pathname:string;public_url:string|null;byte_size:number;updated_at:number};
export function publicMediaEnabled(){return !!token()&&process.env.PRODUCT_MEDIA_DISABLED!=='1'&&process.env.VERCEL_ENV!=='preview'}
function validUrl(url:string,pathname:string){try{const value=new URL(url);return value.protocol==='https:'&&!value.username&&!value.password&&!value.port&&/^[a-z0-9-]+\.public\.blob\.vercel-storage\.com$/.test(value.hostname)&&value.pathname==='/'+pathname&&!value.search&&!value.hash}catch{return false}}
const args=(key:string,size:PhotoPreviewSize)=>[key,size,PUBLIC_MEDIA_PIPELINE];
async function eraseMany(rows:Row[],allowBuilding=false){
 if(!rows.length)return;
 await del(rows.map(row=>row.pathname),{token:token(),abortSignal:AbortSignal.timeout(8000)});
 const removable=rows.filter(row=>allowBuilding||row.public_url||Date.now()-Number(row.updated_at)>=LEASE_MS);
 if(removable.length)await getSqlClient().batch(removable.map(row=>({sql:"DELETE FROM photo_public_derivatives WHERE photo_key=? AND preset=? AND pipeline=? AND state='revoked' AND lease_id=?",args:[row.photo_key,row.preset,row.pipeline,row.lease_id]})),'write');
}
async function erase(row:Row,allowBuilding=false){await eraseMany([row],allowBuilding)}

// Metadata + a short lease prevent the same rendition being generated by many
// Function instances. Reserving the maximum file size bounds parallel growth.
async function claim(key:string,size:PhotoPreviewSize){
 const client=getSqlClient(),cached=(await client.execute({sql:"SELECT * FROM photo_public_derivatives WHERE photo_key=? AND preset=? AND pipeline=? AND state='ready'",args:args(key,size)})).rows[0] as unknown as Row|undefined;
 if(cached)return {ready:cached}; // Ready delivery never takes a write lock.
 const tx=await client.transaction('write');
 try{
  const existing=(await tx.execute({sql:'SELECT * FROM photo_public_derivatives WHERE photo_key=? AND preset=? AND pipeline=?',args:args(key,size)})).rows[0] as unknown as Row|undefined;
  if(existing?.state==='ready'){await tx.commit();return {ready:existing}}
  if(existing?.state==='revoked'){await tx.commit();await erase(existing);return null}
  if(existing&&Date.now()-Number(existing.updated_at)<LEASE_MS){await tx.commit();return null}
  // Expired builders retain a cleanup row; their unique path cannot overwrite a
  // newer generation, and their post-write lease check will remove that asset.
  if(existing){await tx.execute({sql:"UPDATE photo_public_derivatives SET state='revoked' WHERE photo_key=? AND preset=? AND pipeline=?",args:args(key,size)});await tx.commit();await erase({...existing,state:'revoked'});return null}
  const total=Number((await tx.execute({sql:"SELECT COALESCE(SUM(CASE WHEN state!='ready' THEN ? ELSE byte_size END),0) AS bytes FROM photo_public_derivatives",args:[PUBLIC_MEDIA_FILE_LIMIT]})).rows[0].bytes);
  if(total+PUBLIC_MEDIA_FILE_LIMIT>PUBLIC_MEDIA_TOTAL_LIMIT){await tx.commit();return null}
  const lease=crypto.randomUUID(),pathname=`products/${PUBLIC_MEDIA_PIPELINE}/${key}/${size}-${lease}.webp`,now=Date.now();
  await tx.execute({sql:"INSERT INTO photo_public_derivatives(photo_key,preset,pipeline,state,lease_id,pathname,byte_size,updated_at) VALUES(?,?,?,'building',?,?,0,?)",args:[...args(key,size),lease,pathname,now]});
  await tx.commit();return {building:{photo_key:key,preset:size,pipeline:PUBLIC_MEDIA_PIPELINE,state:'building',lease_id:lease,pathname,public_url:null,byte_size:0,updated_at:now} as Row};
 }catch(error){await tx.rollback();throw error}finally{tx.close()}
}

async function retire(row:Row){
 await getSqlClient().execute({sql:"UPDATE photo_public_derivatives SET state='revoked' WHERE photo_key=? AND preset=? AND pipeline=? AND lease_id=?",args:[...args(row.photo_key,row.preset),row.lease_id]});
 await erase({...row,state:'revoked'},true);
}

export async function publicProductMediaUrl(key:string,size:PhotoPreviewSize,loadPreview:(key:string,size:PhotoPreviewSize)=>Promise<PhotoBytes|null>):Promise<string|null>{
 if(!publicMediaEnabled())return null;
 try{
  // Defense in depth: callers cannot publish arbitrary private storage keys.
  if(!/^[a-f0-9-]{36}$/.test(key)||!['thumb','cardSmall','card','detail'].includes(size)||!await publishedPhoto(key))return null;
  const result=await claim(key,size);if(!result)return null;
  if(result.ready)return result.ready.public_url&&validUrl(result.ready.public_url,result.ready.pathname)?result.ready.public_url:null;
  const row=result.building!;
  try{
   const image=await loadPreview(key,size);
   // Decoder fallbacks/small originals are served by the existing private
   // route. Only newly encoded, metadata-stripped WebP can enter this store.
   if(!image?.transformed||image.contentType!=='image/webp'||image.body.byteLength>PUBLIC_MEDIA_FILE_LIMIT||!await publishedPhoto(key)){await retire(row);return null}
   const uploaded=await put(row.pathname,Buffer.from(image.body),{access:'public',token:token(),addRandomSuffix:false,allowOverwrite:false,contentType:'image/webp',cacheControlMaxAge:86400,abortSignal:AbortSignal.timeout(12000)});
   if(!validUrl(uploaded.url,row.pathname))throw new Error('Unexpected product media URL');
   // Recheck publication AND the generation lease after upload. An unpublish
   // or color removal while work was running must never activate that upload.
   const stillPublished=await publishedPhoto(key);
   const changed=stillPublished?await getSqlClient().execute({sql:"UPDATE photo_public_derivatives SET state='ready',public_url=?,byte_size=?,updated_at=? WHERE photo_key=? AND preset=? AND pipeline=? AND state='building' AND lease_id=?",args:[uploaded.url,image.body.byteLength,Date.now(),...args(key,size),row.lease_id]}):null;
   if(!changed?.rowsAffected){await retire(row);return null}
   if(!await publishedPhoto(key)){await retire(row);return null}
   return uploaded.url;
  }catch{await retire(row).catch(()=>{});return null}
 }catch{return null} // A cache/storage outage must not break product images.
}

export function publicProductPhotoKeys(product:Product){
 if(product.status!=='published'||product.deletedAt)return [];
 return [...new Set([product.photoKey,...product.photoKeys??[],...product.colorVariants?.filter(color=>color.active).flatMap(color=>[color.photoKey,color.swatchImage,...color.photoKeys??[]])??[]].filter((key):key is string=>typeof key==='string'&&/^[a-f0-9-]{36}$/.test(key)))];
}

export async function withdrawPublicProductMedia(keys:string[]){
 if(!publicMediaEnabled()||!keys.length)return;
 const withdrawn:Row[]=[];
 for(const key of new Set(keys)){
  // A photo can be shared by another published product or active color.
  if(await publishedPhoto(key))continue;
  const client=getSqlClient();
  await client.execute({sql:"UPDATE photo_public_derivatives SET state='revoked' WHERE photo_key=?",args:[key]});
  const rows=(await client.execute({sql:"SELECT * FROM photo_public_derivatives WHERE photo_key=? AND state='revoked'",args:[key]})).rows as unknown as Row[];
  withdrawn.push(...rows);
 }
 // Blob supports deleting multiple paths in one request. Do not make an admin
 // unpublish wait for one network round trip per image/preset.
 for(let i=0;i<withdrawn.length;i+=100)await eraseMany(withdrawn.slice(i,i+100)).catch(()=>{});
}

// Called only after authenticated catalogue mutations. A bounded retry keeps
// failed deletions durable without adding a cron, polling, or per-photo logs.
export async function retryWithdrawnProductMedia(){
 if(!publicMediaEnabled())return;
 try{const rows=(await getSqlClient().execute("SELECT * FROM photo_public_derivatives WHERE state='revoked' ORDER BY updated_at LIMIT 16")).rows as unknown as Row[];await eraseMany(rows)}catch{}
}
